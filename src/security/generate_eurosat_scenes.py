"""Build the security test data (``test_data/``) on real EuroSAT RGB tiles.

Same 13 guide scenes, 35 edge cases, keys, policy, ledger and expected results as
``generate_test_dataset.py``: only the pictures change. Each synthetic picture is
replaced by a real Sentinel-2 tile from EuroSAT RGB (64 x 64), enlarged x4 by pixel
repetition to the guide's 256 x 256 so that scene 03's red rectangle (pixels 100-140)
lands on the image. No pixel value is invented: every value comes from the tile.
Cases that are deliberately not pictures (empty file, text renamed .png, random bytes,
decompression-bomb header, 7000 x 6000 bilevel PNG) are unchanged.

The manifest metadata (sensor, place, time) is the guide's, not the tile's real
acquisition: EuroSAT RGB carries no georeference. The keys are the same disposable
test keys, so the signing is emulated, as the challenge allows.

    python -m src.security.generate_eurosat_scenes [--eurosat_dir data/raw/eurosat/EuroSAT_RGB]

Without EuroSAT, ``python generate_test_dataset.py`` rebuilds the same cases on
synthetic pictures. Then run the checks from src/security: ``python run_security_cases.py``.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

from PIL import Image

from src.security import generate_test_dataset as gt

EUROSAT_DIR = "data/raw/eurosat/EuroSAT_RGB"
SOURCES: dict[int, str] = {}   # graine de l'image synthetique remplacee -> tuile EuroSAT utilisee


def tile_picker(eurosat_dir: Path):
    classes = sorted(d for d in eurosat_dir.iterdir() if d.is_dir())
    files = [sorted(p for p in c.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png")) for c in classes]
    if len(classes) != 10 or not all(files):
        raise FileNotFoundError(f"EuroSAT RGB introuvable ou incomplet : {eurosat_dir} (10 dossiers de classes attendus).")

    def eurosat_image(seed: int, size: int = 256) -> Image.Image:
        """Meme role que gt.make_scene_image : une classe par graine, tuile tiree au sort, deterministe."""
        pool = files[seed % len(files)]
        path = pool[random.Random(seed).randrange(len(pool))]
        SOURCES[seed] = f"{path.parent.name}/{path.name}"
        tile = Image.open(path).convert("RGB")
        return tile.resize((size, size), Image.NEAREST)

    return eurosat_image


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eurosat_dir", default=EUROSAT_DIR, help="dossier EuroSAT_RGB (un sous-dossier par classe)")
    a = ap.parse_args()
    # Le generateur d'origine lit ces globales a l'appel : on ne remplace que la source des images.
    gt.make_scene_image = tile_picker(Path(a.eurosat_dir))
    gt.LEDGER_PICTURE = gt.encode(gt.make_scene_image(99), "PNG")
    code = gt.main()
    if code:
        return code
    md = gt.OUT / "CASES.md"
    md.write_text(md.read_text(encoding="utf-8").replace(
        "# Synthetic test cases", "# Security test cases on real EuroSAT tiles").replace(
        "Generated by `generate_test_dataset.py`.",
        "Generated by `generate_eurosat_scenes.py` (pictures: real EuroSAT RGB tiles, enlarged x4 by pixel "
        "repetition; the EuroSAT tile behind each generator seed is listed in `sources.json`)."), encoding="utf-8")
    (gt.OUT / "sources.json").write_text(json.dumps({str(k): v for k, v in sorted(SOURCES.items())}, indent=2) + "\n",
                                         encoding="utf-8")
    print(f"{len(SOURCES)} EuroSAT tiles used")
    return 0


if __name__ == "__main__":
    sys.exit(main())
