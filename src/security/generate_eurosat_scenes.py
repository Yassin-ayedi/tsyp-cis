"""The 13 scenes of guide section 7, rebuilt on real EuroSAT RGB tiles.

Same scenes, keys, policy, ledger and expected results as ``generate_test_dataset.py``:
only the pictures change. Each synthetic picture is replaced by a real Sentinel-2 tile
from EuroSAT RGB (64 x 64), enlarged x4 by pixel repetition to the guide's 256 x 256 so
that scene 03's red rectangle (pixels 100-140) lands on the image. No pixel value is
invented: every value comes from the tile.

The manifest metadata (sensor, place, time) is the guide's, not the tile's real
acquisition: EuroSAT RGB carries no georeference. The keys are the same disposable
test keys, so the signing is emulated, as the challenge allows.

    python -m src.security.generate_eurosat_scenes [--eurosat_dir data/raw/eurosat/EuroSAT_RGB]

Writes ``src/security/test_data_eurosat/``; run the checks with
    python run_security_cases.py --data-dir test_data_eurosat --results-dir test_results/eurosat
"""
from __future__ import annotations

import argparse
import json
import random
import shutil
import sys
from pathlib import Path

from PIL import Image

from src.security import generate_test_dataset as gt

OUT = gt.ROOT / "test_data_eurosat"
MARKER = ".generated_by_generate_eurosat_scenes"
EUROSAT_DIR = "data/raw/eurosat/EuroSAT_RGB"
SOURCES: dict[int, str] = {}   # graine de l'image synthetique remplacee -> tuile EuroSAT utilisee


def tile_picker(eurosat_dir: Path):
    classes = sorted(d for d in eurosat_dir.iterdir() if d.is_dir())
    files = [sorted(p for p in c.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png")) for c in classes]
    if len(classes) != 10 or not all(files):
        raise FileNotFoundError(f"EuroSAT RGB introuvable ou incomplet : {eurosat_dir} (10 dossiers de classes attendus).")

    def eurosat_image(seed: int, size: int = 256) -> Image.Image:
        """Meme role que gt.make_scene_image : une classe par graine, tuile tiree au sort, deterministe."""
        pool = files[seed % len(files)]
        path = pool[random.Random(seed).randrange(len(pool))]
        SOURCES[seed] = f"{path.parent.name}/{path.name}"
        tile = Image.open(path).convert("RGB")
        return tile.resize((size, size), Image.NEAREST)

    return eurosat_image


def write_cases_md() -> None:
    lines = ["# Guide scenes on real EuroSAT tiles", "",
             "Generated by `generate_eurosat_scenes.py`. Same scenes and expected results as `test_data/scenes/`; "
             "the pictures are real EuroSAT RGB tiles (Sentinel-2), enlarged x4 by pixel repetition.", "",
             "| Case | Expected status | Reason codes | Description |", "|---|---|---|---|"]
    for c in gt.CASES:
        e = c["expected"]
        lines.append(f"| `{c['case_id']}` | {e['security_status']} | {', '.join(e['reason_codes']) or '-'} | {c['description']} |")
    lines += ["", "EuroSAT tile behind each picture (by generator seed): "
              + ", ".join(f"{k}: `{v}`" for k, v in sorted(SOURCES.items())) + ".",
              "Scene 12 is a text file and has no picture.", ""]
    (OUT / "CASES.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eurosat_dir", default=EUROSAT_DIR, help="dossier EuroSAT_RGB (un sous-dossier par classe)")
    a = ap.parse_args()
    gt._selftest_canonical()
    # Le generateur d'origine lit ces globales a l'appel : on remplace les images et le dossier de sortie.
    gt.make_scene_image = tile_picker(Path(a.eurosat_dir))
    gt.LEDGER_PICTURE = gt.encode(gt.make_scene_image(99), "PNG")
    gt.OUT = OUT
    if OUT.exists():
        if not (OUT / MARKER).exists():
            print(f"refusing to overwrite {OUT}: it was not created by this script", file=sys.stderr)
            return 1
        shutil.rmtree(OUT)
    OUT.mkdir()
    (OUT / MARKER).write_text("Generated test data. Safe to delete and regenerate.\n", encoding="utf-8")
    gt.write_shared_files()
    gt.write_official_scenes()
    write_cases_md()
    (OUT / "sources.json").write_text(json.dumps({str(k): v for k, v in sorted(SOURCES.items())}, indent=2) + "\n",
                                      encoding="utf-8")
    print(f"Wrote {len(gt.CASES)} guide scenes on real EuroSAT tiles to {OUT.relative_to(gt.ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
